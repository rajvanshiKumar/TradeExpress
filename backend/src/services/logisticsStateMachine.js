/**
 * Validates whether transition from currentStatus to targetStatus is permitted for userRole.
 * @returns {{ valid: boolean, error?: string }}
 */
export function validateStatusTransition(currentStatus, targetStatus, userRole) {
  const normCurrent = (currentStatus || '').toUpperCase();
  const normTarget = (targetStatus || '').toUpperCase();
  const normRole = (userRole || '').toUpperCase();

  if (!ALLOWED_TRANSITIONS[normCurrent]) {
    return {
      valid: false,
      error: `Invalid current shipment status '${normCurrent}'.`,
    };
  }

  const allowedNext = ALLOWED_TRANSITIONS[normCurrent];
  if (!allowedNext.includes(normTarget)) {
    if (['PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY'].includes(normTarget) && normCurrent === SHIPMENT_STATUSES.DOCUMENTS_PENDING) {
      return {
        valid: false,
        error: 'Shipment cannot be dispatched. Required Super Admin verification must be complete before dispatch.',
      };
    }
    return {
      valid: false,
      error: `Transition from '${normCurrent}' to '${normTarget}' is not allowed. Permitted: [${allowedNext.join(', ')}].`,
    };
  }

  // Super Admin can override transition rules
  if (normRole === 'SUPER_ADMIN') {
    return { valid: true };
  }

  const authorizedRoles = STATUS_PERMISSION_RULES[normTarget] || ['ADMIN', 'SUPER_ADMIN'];
  if (!authorizedRoles.includes(normRole)) {
    return {
      valid: false,
      error: `Role '${normRole}' is not authorized to set status to '${normTarget}'. Required: [${authorizedRoles.join(', ')}].`,
    };
  }

  return { valid: true };
}

